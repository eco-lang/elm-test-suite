#!/usr/bin/env python3
"""Writes StandardElmMech/NoStuck.lean: for each logged relation of RulesL.lean, the theorem
`nostuck` (plan decision D1): for a derivation with value w and log l, the evaluator, at any oracle
o, fuel n and index k, runs out of fuel, or reads a choice (its next index is above k), or gives
exactly w and l without reading a choice. One mutual block, one case per constructor, generated from
RulesL.lean like Forget.lean (scripts/gen_forget.py); the build checks it.

Run from the project folder:  python3 scripts/gen_nostuck.py
"""
import re

exec(open('scripts/gen_forget.py').read().split("out = []")[0])  # relations, ctors, split_top

EVAL = {
    'EvalAtExpL': 'evAtExp', 'EvalExpRowL': 'evExpRow', 'EvalExpL': 'evExp', 'AppValL': 'appVal',
    'EvalMatchL': 'evMatch', 'EvalMRuleL': 'evMRule', 'EvalDecL': 'evDec',
    'EvalValBindL': 'evValBind', 'MatchAtPatL': 'matchAtPat', 'MatchPatRowL': 'matchPatRow',
    'MatchPatL': 'matchPat', 'EvalExpOptL': 'evExpOpt', 'EvalExpRowOptL': 'evExpRowOpt',
    'EvalValBindOptL': 'evValBindOpt', 'MatchPatOptL': 'matchPatOpt',
    'MatchPatRowOptL': 'matchPatRowOpt', 'MatchAtPatsL': 'matchAtPats',
}

out = []
out.append('/-\n  Generated by scripts/gen_nostuck.py from RulesL.lean. Do not edit.\n\n'
           '  `nostuck`: for a derivation of a logged relation with value w and log l, the evaluator at\n'
           '  any oracle, fuel and index k runs out of fuel, reads a choice, or gives exactly w and l\n'
           '  without reading one (plan decision D1). By induction on the derivation.\n-/\n'
           'import StandardElmMech.Complete\n\nnamespace StandardElm\n')
out.append('set_option maxHeartbeats 1000000\n')
out.append('mutual\n')
for rel, sig in relations:
    idx = [x.strip() for x in split_top(sig, '→')]
    nidx = len(idx) - 1
    xs = [f'x{i}' for i in range(nidx)]
    args, val, log = xs[:-2], xs[-2], xs[-1]
    f = EVAL[rel]
    out.append(f'theorem {rel}.nostuck : ∀ {{{" ".join(xs)}}}, {rel} {" ".join(xs)} →\n'
               f'    ∀ (o : Oracle) (n k : Nat) r, {f} o n {" ".join(args)} k = r →\n'
               f'      r.out = .outOfFuel ∨ k < r.next ∨ r = ⟨.value {val}, {log}, k⟩')
    for (r, name, cargs, premises) in ctors:
        if r != rel:
            continue
        hs = [f'h{i}' for i in range(len(premises))]
        pat_args = ' '.join(a for a, _ in cargs)
        lines = [f'  | {", ".join("_" for _ in xs)}, .{name} {pat_args} {" ".join(hs)} => by',
                 '      intro oo n k res h',
                 '      cases n with',
                 f'      | zero => subst h; simp [{f}]',
                 '      | succ mm =>']
        for i, (h, p) in enumerate(zip(hs, premises)):
            toks = [t for t in split_top(p, ' ') if t]
            head = toks[0]
            if head in EVAL:
                pa, pv, pl = toks[1:-2], toks[-2], toks[-1]
                pf = EVAL[head]
                lines.append(f'        have p{i} : NS ({pf} oo mm {" ".join(pa)}) {pv} {pl} :=')
                lines.append(f'          fun hh => {head}.nostuck {h} oo mm _ _ hh')
            elif head == 'Apply':
                lines.append(f'        have ha{i} := applySet_complete {h}')
            elif head == 'MatchAtPatsL':
                pass
        if any(split_top(p, ' ')[0] == 'MatchAtPatsL' for p in premises):
            for h, p in zip(hs, premises):
                if split_top(p, ' ')[0] == 'MatchAtPatsL':
                    lines.append(f'        have hlen := MatchAtPatsL.length_eq {h}')
        pnames = [f'p{i}' for i, p in enumerate(premises) if split_top(p, ' ')[0] in EVAL]
        lines.append(f'        simp only [{f}] at h')
        if len(pnames) == 1:
            lines.append(f'        try (subst h; exact {pnames[0]} rfl)')
        lines.append(f'        ns_fin [{", ".join(pnames)}]')
        out.extend(lines)
out.append('end\n')
out.append('end StandardElm\n')
open('StandardElmMech/NoStuck.lean', 'w').write('\n'.join(out))
print(f'StandardElmMech/NoStuck.lean: {len(relations)} relations, {len(ctors)} constructors')
