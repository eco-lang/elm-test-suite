#!/usr/bin/env python3
"""Writes StandardElmMech/Completeness.lean: for each logged relation of RulesL.lean, the theorem
`complete` (plan decision D1): every derivation, with its value w and log l, is found by the
evaluator: there are choices L and a fuel n such that, for every oracle that makes the choices L
from index k on and every fuel m >= n, the evaluator gives exactly w and l and reads the |L|
choices. One mutual block, one case per constructor, generated from RulesL.lean like Forget.lean;
the build checks it. Run from the project folder:  python3 scripts/gen_complete.py
"""
import re

exec(open('scripts/gen_forget.py').read().split("out = []")[0])  # relations, ctors, split_top

EVAL = {
    'EvalAtExpL': 'evAtExp', 'EvalExpRowL': 'evExpRow', 'EvalExpL': 'evExp', 'AppValL': 'appVal',
    'EvalMatchL': 'evMatch', 'EvalMRuleL': 'evMRule', 'EvalDecL': 'evDec',
    'EvalValBindL': 'evValBind', 'MatchAtPatL': 'matchAtPat', 'MatchPatRowL': 'matchPatRow',
    'MatchPatL': 'matchPat', 'EvalExpOptL': 'evExpOpt', 'EvalExpRowOptL': 'evExpRowOpt',
    'EvalValBindOptL': 'evValBindOpt', 'MatchPatOptL': 'matchPatOpt',
    'MatchPatRowOptL': 'matchPatRowOpt', 'MatchAtPatsL': 'matchAtPats',
}

out = []
out.append('/-\n  Generated by scripts/gen_complete.py from RulesL.lean. Do not edit.\n\n'
           '  `complete`: every derivation of a logged relation, with its value w and log l, is found by\n'
           '  the evaluator: for some choices L and fuel n, every oracle that makes the choices L from\n'
           '  index k on gives, at every fuel m >= n, exactly w and l, reading the |L| choices\n'
           '  (plan decision D1). By induction on the derivation.\n-/\n'
           'import StandardElmMech.Complete\n\nnamespace StandardElm\n')
out.append('set_option maxHeartbeats 1000000\n-- the cases share one generated simp set, so not every argument is used in every case\nset_option linter.unusedSimpArgs false\n')
out.append('mutual\n')
for rel, sig in relations:
    idx = [x.strip() for x in split_top(sig, '→')]
    nidx = len(idx) - 1
    xs = [f'x{i}' for i in range(nidx)]
    args, val, log = xs[:-2], xs[-2], xs[-1]
    f = EVAL[rel]
    out.append(f'theorem {rel}.complete : ∀ {{{" ".join(xs)}}}, {rel} {" ".join(xs)} →\n'
               f'    ∃ (L : List Bool) (n : Nat), ∀ (oo : Oracle) (k m : Nat), n ≤ m → Agrees oo k L →\n'
               f'      {f} oo m {" ".join(args)} k = ⟨.value {val}, {log}, k + L.length⟩')
    for (r, name, cargs, premises) in ctors:
        if r != rel:
            continue
        hs = [f'h{i}' for i in range(len(premises))]
        pat_args = ' '.join(a for a, _ in cargs)
        argnames = [a for a, _ in cargs]
        lines = [f'  | {", ".join("_" for _ in xs)}, .{name} {pat_args} {" ".join(hs)} => by']
        if name == 'r_d_app_basic_apply_l':
            lines += [
                '      have hm := applySet_complete h1',
                '      have hl := applySet_length_le_two b (vs ++ [v])',
                '      rcases happ : applySet b (vs ++ [v]) with _ | ⟨w, _ | ⟨w2, ws⟩⟩',
                '      · rw [happ] at hm; simp at hm',
                '      · rw [happ] at hm; simp at hm; subst hm',
                '        refine ⟨[], 1, ?_⟩',
                '        intro oo k m hm' + "'" + ' _',
                "        obtain ⟨mm, rfl⟩ : ∃ mm, m = mm + 1 := ⟨m - 1, by omega⟩",
                '        simp [appVal, h0, happ]',
                '      · rw [happ] at hm hl',
                '        simp at hl hm',
                '        subst hl',
                '        rcases hm with rfl | hm2',
                '        · refine ⟨[false], 1, ?_⟩',
                "          intro oo k m hm' hag",
                "          obtain ⟨mm, rfl⟩ : ∃ mm, m = mm + 1 := ⟨m - 1, by omega⟩",
                '          simp [appVal, h0, happ, agrees_single hag]',
                '        · simp at hm2; subst hm2',
                '          refine ⟨[true], 1, ?_⟩',
                "          intro oo k m hm' hag",
                "          obtain ⟨mm, rfl⟩ : ∃ mm, m = mm + 1 := ⟨m - 1, by omega⟩",
                '          simp [appVal, h0, happ, agrees_single hag]',
            ]
            out.extend(lines)
            continue
        rel_prem = []   # (h, head, args)
        sides = []
        substs = []
        extra = []
        for h, p in zip(hs, premises):
            toks = [t for t in split_top(p, ' ') if t]
            head = toks[0]
            if head in EVAL:
                rel_prem.append((h, head, toks[1:-2]))
                if head == 'MatchAtPatsL':
                    extra.append(f'      have hlen := MatchAtPatsL.length_eq {h}')
                    sides += ['hlen', 'conArgs', 'and_self', 'true_and', 'ite_true', 'eq_self_iff_true']
            elif re.match(r'^\w+ = ', p) and p.split(' = ')[0] in argnames:
                substs.append(h)
            elif p.startswith('(¬ ∃'):
                extra.append(f'      have hn := conArgs_none_of {h}')
                sides.append('hn')
            else:
                sides.append(h)
        for i, (h, head, pa) in enumerate(rel_prem):
            lines.append(f'      obtain ⟨L{i}, n{i}, c{i}⟩ := {head}.complete {h}')
        lines.extend(extra)
        for h in substs:
            lines.append(f'      subst {h}')
        k = len(rel_prem)
        Ls = ' ++ '.join(f'L{i}' for i in range(k)) if k else '[]'
        ns = 'n0' if k == 1 else ('max n0 n1' if k == 2 else ('max n0 (max n1 n2)' if k == 3 else '0'))
        lines.append(f'      refine ⟨{Ls}, {ns} + 1, ?_⟩')
        lines.append('      intro oo k m hm hag')
        lines.append("      obtain ⟨mm, rfl⟩ : ∃ mm, m = mm + 1 := ⟨m - 1, by omega⟩")
        if k == 2:
            lines.append('      obtain ⟨a0, a1⟩ := agrees2 hag')
        elif k == 3:
            lines.append('      obtain ⟨a0, a1, a2⟩ := agrees3 hag')
        elif k == 1:
            lines.append('      have a0 := hag')
        side = ', '.join(sides + ['sconTest_iff', 'conIs_iff'])
        lines.append(f'      simp only [{f}]')
        idxs = ['k', 'k + L0.length', 'k + L0.length + L1.length']
        for i in range(k):
            lines.append(f'      try simp only [{side}]')
            lines.append(f'      rw [c{i} oo ({idxs[i]}) mm (by omega) a{i}]')
            lines.append('      try dsimp only')
        lines.append(f'      try simp only [{side}]')
        lines.append(f'      try simp [{side}, List.length_append, Nat.add_assoc]')
        lines.append('      try omega')
        out.extend(lines)
out.append('end\n')
out.append('end StandardElm\n')
open('StandardElmMech/Completeness.lean', 'w').write('\n'.join(out))
print(f'StandardElmMech/Completeness.lean: {len(relations)} relations, {len(ctors)} constructors')
