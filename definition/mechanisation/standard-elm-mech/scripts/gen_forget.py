#!/usr/bin/env python3
"""Writes StandardElmMech/Forget.lean: the theorems `forget` (a derivation of a logged relation of
RulesL.lean gives a derivation of the book's relation of Rules.lean, with the same value) and `lift`
(every derivation of the book has a logged one), one mutual block each, one case per constructor.

The cases are mechanical, so they are generated from RulesL.lean rather than written by hand; the
build checks them. Run from the project folder:  python3 scripts/gen_forget.py
"""
import re
import sys

SRC = 'StandardElmMech/RulesL.lean'
OUT = 'StandardElmMech/Forget.lean'

text = open(SRC).read()
body = text[text.index('mutual'):text.rindex('end StandardElm')]

relations = re.findall(r'^inductive (\w+L) : (.*?) where', body, re.M)
rel_names = [r for r, _ in relations]


def split_top(s, sep):
    """Split s on sep at bracket depth 0."""
    out, depth, cur, i = [], 0, '', 0
    while i < len(s):
        ch = s[i]
        if ch in '([{⟨':
            depth += 1
        elif ch in ')]}⟩':
            depth -= 1
        if depth == 0 and s.startswith(sep, i):
            out.append(cur)
            cur = ''
            i += len(sep)
            continue
        cur += ch
        i += 1
    out.append(cur)
    return out


ctors = []  # (relation, name, args [(name, type)], premises [str])
for rel, _ in relations:
    block = body[body.index(f'inductive {rel} '):]
    nxt = re.search(r'^inductive ', block[10:], re.M)
    block = block[: 10 + nxt.start()] if nxt else block
    for m in re.finditer(r'^\s*\|\s*(\w+)(.*?)(?=^\s*\||\Z)', block, re.M | re.S):
        name, rest = m.group(1), m.group(2)
        if '/--' in rest:
            rest = rest[:rest.index('/--')]
        rest = ' '.join(rest.split())
        pieces = split_top(rest, ' : ')
        head, sig = pieces[0], ' : '.join(pieces[1:])
        args = []
        for grp in re.findall(r'\(([^()]*?) : ([^()]*(?:\([^()]*\)[^()]*)*)\)', head):
            for a in grp[0].split():
                args.append((a, grp[1].strip()))
        parts = [p.strip() for p in split_top(sig, '→')]
        premises = parts[:-1]
        ctors.append((rel, name, args, premises))


def book(rel):
    return rel[:-1]


def is_rel_premise(p):
    h = p.split()[0]
    return h in rel_names


out = []
out.append('/-\n  Generated by scripts/gen_forget.py from RulesL.lean. Do not edit.\n\n'
           '  `forget`: a derivation of a logged relation gives a derivation of the book\'s relation with\n'
           '  the same value. `lift`: every derivation of the book has a logged one (with some log).\n'
           '  Both by structural recursion on the derivation, one case per rule (plan decision D4).\n-/\n'
           'import StandardElmMech.RulesL\n\nnamespace StandardElm\n')

# forget
out.append('mutual\n')
for rel, sig in relations:
    idx = [x.strip() for x in split_top(sig, '→')]
    nidx = len(idx) - 1  # without Prop
    vars_ = [f'x{i}' for i in range(nidx)]
    out.append(f'theorem {rel}.forget : ∀ {{{" ".join(vars_)}}}, {rel} {" ".join(vars_)} → {book(rel)} {" ".join(vars_[:-1])}')
    for (r, name, args, premises) in ctors:
        if r != rel:
            continue
        hs = [f'h{i}' for i in range(len(premises))]
        pat_args = ' '.join(a for a, _ in args)
        book_args = ' '.join(a for a, t in args if t != 'Log')
        call = []
        for h, p in zip(hs, premises):
            call.append(f'({p.split()[0]}.forget {h})' if is_rel_premise(p) else h)
        bname = name[:-2]
        out.append(f'  | {", ".join("_" for _ in vars_)}, .{name} {pat_args} {" ".join(hs)} =>'
                   f'\n    .{bname} {book_args} {" ".join(call)}'.rstrip())
out.append('end\n')

# lift
out.append('mutual\n')
for rel, sig in relations:
    idx = [x.strip() for x in split_top(sig, '→')]
    nidx = len(idx) - 2  # without the log and Prop
    vars_ = [f'x{i}' for i in range(nidx)]
    out.append(f'theorem {book(rel)}.lift : ∀ {{{" ".join(vars_)}}}, {book(rel)} {" ".join(vars_)} → ∃ l, {rel} {" ".join(vars_)} l')
    for (r, name, args, premises) in ctors:
        if r != rel:
            continue
        hs = [f'h{i}' for i in range(len(premises))]
        book_args = ' '.join(a for a, t in args if t != 'Log')
        logs = [a for a, t in args if t == 'Log']
        bname = name[:-2]
        lets = []
        call = []
        li = 0
        for h, p in zip(hs, premises):
            if is_rel_premise(p):
                lets.append(f'    let ⟨{logs[li]}, {h}l⟩ := {book(p.split()[0])}.lift {h}')
                call.append(f'{h}l')
                li += 1
            else:
                call.append(h)
        all_args = ' '.join(a for a, _ in args)
        out.append(f'  | {", ".join("_" for _ in vars_)}, .{bname} {book_args} {" ".join(hs)} =>')
        out.extend(lets)
        out.append(f'    ⟨_, .{name} {all_args} {" ".join(call)}⟩')
out.append('end\n')

out.append('end StandardElm\n')
open(OUT, 'w').write('\n'.join(out))
print(f'{OUT}: {len(relations)} relations, {len(ctors)} constructors')
