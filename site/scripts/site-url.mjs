// Writes src/SiteUrl.elm, the site's address, from the environment variable SITE_URL (default: the
// production site). Links that leave the site and come back (link previews' og:image, the link back
// in a new GitHub discussion, the canonical address) are made from it, so a staging build must
// point at the staging site. Run before every build and dev server (npm's prebuild and prestart).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT = 'https://elm-test-suite.netlify.app';
const url = (process.env.SITE_URL || DEFAULT).trim().replace(/\/+$/, '');
if (!/^https?:\/\/[^\s"\\]+$/.test(url)) {
    console.error('site-url.mjs: SITE_URL is not an http(s) address: ' + url);
    process.exit(2);
}
const file = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'SiteUrl.elm');
const elm = `module SiteUrl exposing (siteUrl)

{-| Generated by scripts/site-url.mjs from SITE_URL; not tracked by git.
-}


siteUrl : String
siteUrl =
    "${url}"
`;
const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
if (old !== elm) fs.writeFileSync(file, elm);
console.log('site address: ' + url);
